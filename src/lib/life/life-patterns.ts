export function nameSeed() {
  const cells = new Uint8Array(120 * 52);
  ['ANKIT', 'KUMAR'].forEach((word, row) =>
    [...word].forEach((char, col) =>
      glyphs[char].forEach((line, y) =>
        [...line].forEach((value, x) => {
          if (value === '1') {
            [0, 1].forEach((dy) =>
              [0, 1].forEach((dx) => {
                cells[(7 + row * 23 + y * 2 + dy) * 120 + 10 + col * 21 + x * 2 + dx] = 1;
              }),
            );
          }
        }),
      ),
    ),
  );
  return cells;
}
export function gliderSeed() {
  const cells = new Uint8Array(16 * 8);
  [
    [2, 1],
    [3, 2],
    [1, 3],
    [2, 3],
    [3, 3],
    [11, 3],
    [11, 4],
    [11, 5],
  ].forEach(([x, y]) => (cells[y * 16 + x] = 1));
  return cells;
}
